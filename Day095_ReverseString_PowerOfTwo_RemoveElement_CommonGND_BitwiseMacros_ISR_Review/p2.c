// 難度：🟢 系統廠高頻基本題 | 出題頻率：🔥🔥🔥🔥🔥 (系統廠/硬體韌體位元運算必考題)
// 題目說明：給你一個整數 n，請你判斷該整數是否是 2 的冪次方。
//           如果是，返回 true；否則，返回 false。
//           如果存在一個整數 x 使得 n == 2^x，則認為 n 是 2 的冪次方。
// 範例 1：
//    輸入：n = 1
//    輸出：true
//    解釋：2^0 = 1
// 範例 2：
//    輸入：n = 16
//    輸出：true
//    解釋：2^4 = 16
// 範例 3：
//    輸入：n = 3
//    輸出：false
// 範例 4：
//    輸入：n = 0
//    輸出：false
// 限制條件：
//    - -2^31 <= n <= 2^31 - 1
//    - ⚠️ 目標挑戰：能否不用迴圈/遞迴，僅使用 O(1) 的位元運算（Bitwise）技巧一行搞定？
// ============================================================================

bool isPowerOfTwo(int n) {
    // TODO: 請在純白板模式下完成實作 (請勿尋求提示)
    return (n > 0) && ((n & (n - 1)) == 0);
}

/*
 * ============================================================================
 * 🔍 原始盲點檢討 (Mistake Analysis Archive)
 * ============================================================================
 * 【原始寫法】：
 *     return (x & (x - 1) == 0);
 * 
 * 【三大盲點剖析】：
 *   1. 變數名稱錯誤 (Compile Error)：
 *      函式參數宣告為 `int n`，但程式碼中誤寫為 `x`，造成編譯器報錯 (undeclared identifier)。
 *   2. 運算子優先級陷阱 (Operator Precedence Bug)：
 *      在 C 語言中，關係運算子 `==` 的優先級高於位元運算子 `&`！
 *      `n & (n - 1) == 0` 實際上會被解析為 `n & ((n - 1) == 0)`：
 *      - 例如 n=16 時，(15 == 0) 為 0，運算變成 16 & 0 = 0 (回傳 false，判定失真)。
 *      - 修正必須為位元運算加上括號：`((n & (n - 1)) == 0)`。
 *   3. 零與負數邊界漏失 (Edge Cases: n <= 0)：
 *      - 當 n = 0 時，0 不是 2 的冪次方，但 `(0 & (0 - 1)) == 0` 會錯誤回傳 true。
 *      - 當 n = -2147483648 (INT_MIN) 時，n - 1 會引發有號整數溢位 (Signed Overflow / UB)。
 *      - 2 的冪次方本質上恆正 ($2^x > 0$)，因此必須在最前面加入 `n > 0` 短路保護。
 * 
 * 【修正方式】：
 *     return (n > 0) && ((n & (n - 1)) == 0);
 * ============================================================================
 */

int main(void) {
    /* 測試測資 1: 1 -> true */
    printf("測資 1 (n=1)  : %s (預期: true)\n", isPowerOfTwo(1) ? "true" : "false");

    /* 測試測資 2: 16 -> true */
    printf("測資 2 (n=16) : %s (預期: true)\n", isPowerOfTwo(16) ? "true" : "false");

    /* 測試測資 3: 3 -> false */
    printf("測資 3 (n=3)  : %s (預期: false)\n", isPowerOfTwo(3) ? "true" : "false");

    /* 測試測資 4: 0 -> false (邊界) */
    printf("測資 4 (n=0)  : %s (預期: false)\n", isPowerOfTwo(0) ? "true" : "false");

    /* 測試測資 5: -16 -> false (負數邊界) */
    printf("測資 5 (n=-16): %s (預期: false)\n", isPowerOfTwo(-16) ? "true" : "false");

    return 0;
}
