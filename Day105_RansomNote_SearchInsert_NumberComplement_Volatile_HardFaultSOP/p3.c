#include <stdio.h>

/**
 * ============================================================================
 * 【Day 105 - 題目三】數字的補數 (LeetCode #476 - Number Complement)
 * 【考試頻率】群聯 (Phison) SSD 韌體 / 系統廠 暫存器遮罩經典位元題
 * 【LeetCode 難度】Easy (初階精準題)
 * ============================================================================
 * 【題目說明】
 * 給定一個正整數 num，輸出它的補數。
 * 補數的定義是：將其二進位表示中的每一位進行翻轉（0 變 1，1 變 0），但「不翻轉前導零（Leading Zeros）」。
 * 
 * 【範例 1】
 * 輸入: num = 5
 * 輸出: 2
 * 解釋:
 * 5 的二進位表示是 101（沒有前導零位元）。
 * 其補數為 010，也就是十進位的 2。
 * 
 * 【範例 2】
 * 輸入: num = 1
 * 輸出: 0
 * 解釋:
 * 1 的二進位表示是 1。
 * 其補數為 0，也就是十進位的 0。
 * 
 * 【限制條件】
 * 1. 1 <= num < 2^31
 * ============================================================================
 */

int findComplement(int num) {
    // 韌體最優解：動態生成與 num 等長的連續全 1 遮罩 (Bitmask)
    // 例如 num = 5 (101_2)，生成的 mask = 7 (111_2)
    // 接著使用 XOR (num ^ mask) 即可完美翻轉所有有效位元！
    unsigned int mask = 1;
    while (mask < num) {
        mask = (mask << 1) | 1;
    }
    return num ^ mask;
}

