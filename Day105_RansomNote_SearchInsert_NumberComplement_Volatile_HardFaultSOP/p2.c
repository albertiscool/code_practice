#include <stdio.h>

/**
 * ============================================================================
 * 【Day 105 - 題目二】搜尋插入位置 (LeetCode #35 - Search Insert Position)
 * 【考試頻率】群聯 (Phison) / 系統廠 (廣達、緯創、和碩) 經典二分搜尋邊界題
 * 【LeetCode 難度】Easy (初階精準題)
 * ============================================================================
 * 【題目說明】
 * 給定一個排序陣列 nums 和一個目標值 target，在陣列中找到目標值，並回傳其索引。
 * 如果目標值不存在於陣列中，回傳它將會被按順序插入的位置。
 * 
 * ⚠️ 限制條件：
 * 必須撰寫一個時間複雜度為 O(log n) 的演算法。
 * 
 * 【範例 1】
 * 輸入: nums = [1,3,5,6], target = 5
 * 輸出: 2
 * 
 * 【範例 2】
 * 輸入: nums = [1,3,5,6], target = 2
 * 輸出: 1
 * 
 * 【範例 3】
 * 輸入: nums = [1,3,5,6], target = 7
 * 輸出: 4
 * 
 * 【限制條件】
 * 1. 1 <= nums.length <= 10^4
 * 2. -10^4 <= nums[i] <= 10^4
 * 3. nums 為無重複元素的升序排列陣列
 * 4. -10^4 <= target <= 10^4
 * ============================================================================
 */

int searchInsert(int* nums, int numsSize, int target) {
    int left = 0;
    int right = numsSize - 1;
    while (left <= right) {
        // 韌體最佳實務：避免 (left + right) 整數溢位
        int mid = left + (right - left) / 2;
        if (nums[mid] == target) {
            return mid;
        } else if (nums[mid] < target) {
            left = mid + 1;
        } else {
            right = mid - 1;
        }
    }
    // 迴圈結束時 left > right，left 正好就是 target 該插入的第一個大於它的位置
    return left;
}

