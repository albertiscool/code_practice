#include <stdio.h>
#include <stdint.h>

/**
 * ============================================================================
 * 題目二：顛倒 32 位元無號整數 (LeetCode #190 - Reverse Bits)
 * ============================================================================
 * 【難度頻率】群聯、慧榮、瑞昱、聯發科韌體/底層暫存器操作必考題
 * 
 * 【題目說明】
 * 給定一個 32 位元無號整數 n，請將其 32 個 binary bits 前後完全顛倒。
 * 也就是：
 * - Bit 0  與 Bit 31 對調
 * - Bit 1  與 Bit 30 對調
 * - ...
 * - Bit 15 與 Bit 16 對調
 * 回傳顛倒後的 32 位元無號整數。
 * 
 * 【範例 1】
 * 輸入: n = 43261596
 * 二進位輸入: 00000010100101000001111010011100
 * 二進位輸出: 00111001011110000010100101000000
 * 數值輸出: 964176192
 * 
 * 【範例 2】
 * 輸入: n = 1
 * 二進位輸入: 00000000000000000000000000000001
 * 二進位輸出: 10000000000000000000000000000000
 * 數值輸出: 2147483648 (即 1U << 31)
 * 
 * 【延伸思維】
 * 1. 基礎解法：迴圈走 32 次 bit-by-bit 移位。
 * 2. 進階解法：Divide and Conquer (分治遮罩交換法，類似硬體平行交換)。
 * ============================================================================
 */

uint32_t reverseBits(uint32_t n) {
    if (n == 0) {
        return 0;
    }
    uint32_t result = 0;
    for (int i = 0; i < 32; i++) {
        result = (result << 1) | (n & 1);
        n >>= 1; // 修正關鍵：必須賦值回 n (n = n >> 1)，否則運算結果被丟棄！
    }
    return result;
}

/**
 * ============================================================================
 * 【一線 IC 設計廠進階加分追問：O(1) 分治平行位元翻轉 (Divide and Conquer)】
 * ============================================================================
 * 面試官追問：「如果這個函式一秒要被呼叫上億次，迴圈跑 32 次太慢，怎麼在 5 步內完成？」
 * 原理：如同歸併排序逆向，兩兩對調：
 * 1. 交換 16 位元前後半
 * 2. 交換 8 位元前後半 (Byte)
 * 3. 交換 4 位元前後半 (Nibble)
 * 4. 交換 2 位元前後半
 * 5. 交換 1 位元前後半
 */
uint32_t reverseBits_Fast(uint32_t n) {
    n = ((n & 0xFFFF0000) >> 16) | ((n & 0x0000FFFF) << 16);
    n = ((n & 0xFF00FF00) >> 8)  | ((n & 0x00FF00FF) << 8);
    n = ((n & 0xF0F0F0F0) >> 4)  | ((n & 0x0F0F0F0F) << 4);
    n = ((n & 0xCCCCCCCC) >> 2)  | ((n & 0x33333333) << 2);
    n = ((n & 0xAAAAAAAA) >> 1)  | ((n & 0x55555555) << 1);
    return n;
}

int main(void) {
    printf("=== Day 102 P2: Reverse Bits 驗證 ===\n");

    // 測試 1：43261596 -> 964176192
    uint32_t n1 = 43261596;
    printf("測試 1 輸入: %u\n", n1);
    printf("測試 1 輸出 (迴圈法): %u\n", reverseBits(n1));
    printf("測試 1 輸出 (分治法): %u\n", reverseBits_Fast(n1));

    // 測試 2：1 -> 2147483648 (1U << 31)
    uint32_t n2 = 1;
    printf("\n測試 2 輸入: %u\n", n2);
    printf("測試 2 輸出 (迴圈法): %u\n", reverseBits(n2));
    printf("測試 2 輸出 (分治法): %u\n", reverseBits_Fast(n2));

    // 測試 3：0 -> 0
    uint32_t n3 = 0;
    printf("\n測試 3 輸入: %u\n", n3);
    printf("測試 3 輸出 (迴圈法): %u\n", reverseBits(n3));
    printf("測試 3 輸出 (分治法): %u\n", reverseBits_Fast(n3));

    return 0;
}

