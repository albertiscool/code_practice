/**
 * Definition for singly-linked list.
 * struct ListNode {
 *     int val;
 *     struct ListNode *next;
 * };
 */

/* 
 * 你的實作（反轉鏈結串列法，0 ms Beats 100% AC）：
 * 亮點：靈活調用先前練習的反轉鏈結串列三指標技術，將 MSB->LSB 轉為 LSB->MSB 後依權重累加！
 */
int getDecimalValue(struct ListNode* head) {
    struct ListNode* pre = NULL;
    struct ListNode* curr = head;
    while (curr != NULL) {
        struct ListNode* next_node = curr->next;
        curr->next = pre;
        pre = curr;
        curr = next_node;
    }
    
    int count = 0;
    int result = 0;
    while (pre != NULL) {
        if (pre->val == 1) {
            result += (1 << count);
        }
        count++;
        pre = pre->next;
    }
    return result;
}

