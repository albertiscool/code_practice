#include <stdio.h>
#include <stdlib.h>

/**
 * ============================================================================
 * 【Day 107 - 題目二】按奇偶排序陣列 (LeetCode #905 - Sort Array By Parity)
 * 【考試頻率】電子五哥 (廣達 Quanta、緯創 Wistron、仁寶 Compal) 白板演算法經典題
 * 【LeetCode 難度】Easy (原地雙指標分區題)
 * ============================================================================
 * 【題目說明】
 * 給定一個非負整數陣列 nums。
 * 請將陣列重新排列，使得所有的「偶數元素」排在陣列的「前半部」，
 * 所有的「奇數元素」排在陣列的「後半部」。
 * 
 * 回傳滿足上述條件的任何一個排列皆可（偶數之間與奇數之間的相對順序不限）。
 * 
 * ⚠️ 韌體考官要求：請盡可能以原地操作（In-place, O(1) 額外記憶體）完成。
 * 
 * 【範例 1】
 * 輸入: nums = [3, 1, 2, 4]
 * 輸出: [2, 4, 3, 1]
 * 解釋: [4, 2, 3, 1]、[2, 4, 1, 3] 和 [4, 2, 1, 3] 也都會被判定為正確。
 * 
 * 【範例 2】
 * 輸入: nums = [0]
 * 輸出: [0]
 * 
 * 【限制條件】
 * 1. 1 <= nums.length <= 5000
 * 2. 0 <= nums[i] <= 5000
 * ============================================================================
 */

/**
 * Note: The returned array must be malloced, assume caller calls free().
 */

int* sortArrayByParity(int* nums, int numsSize, int* returnSize) {
    // 請在此處撰寫你的程式碼
    *returnSize = numsSize;
    int slow = 0;
    int fast = 0;
    while (fast < numsSize) {
        // 💡 韌體小優化：在無硬體除法器的低階 MCU 上，可寫成 ((nums[fast] & 1) == 0)
        if ((nums[fast] % 2) == 0) {
            int temp = nums[fast];
            nums[fast] = nums[slow];
            nums[slow] = temp;
            slow++;
        }
        fast++;
    }
    return nums;
}

