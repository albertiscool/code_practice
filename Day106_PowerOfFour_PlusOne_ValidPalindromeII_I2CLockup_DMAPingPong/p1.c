/**
 * ============================================================================
 * 【Day 106 - 題目一】4 的冪 (LeetCode #342 - Power of Four)
 * 【考試頻率】群聯 (Phison) SSD 韌體 / 系統廠 經典位元遮罩與運算題
 * 【LeetCode 難度】Easy (初階精準題)
 * ============================================================================
 * 【題目說明】
 * 給定一個整數 n，如果它是 4 的冪次方，回傳 true；否則回傳 false。
 * 如果存在一個整數 x 使得 n == 4^x，則整數 n 是 4 的冪次方。
 * 
 * ⚠️ 韌體加分條件：
 * 面試官最愛追問：「你能不用任何迴圈或遞迴（Loop / Recursion），以 O(1) 的位元運算完成嗎？」
 * 
 * 【範例 1】
 * 輸入: n = 16
 * 輸出: true
 * 
 * 【範例 2】
 * 輸入: n = 5
 * 輸出: false
 * 
 * 【範例 3】
 * 輸入: n = 1
 * 輸出: true (4^0 = 1)
 * 
 * 【限制條件】
 * 1. -2^31 <= n <= 2^31 - 1
 * ============================================================================
 */

bool isPowerOfFour(int n) {
    // 1. (n > 0)：排除 0 與負數 (4^x 必然為正整數)
    // 2. ((n & (n - 1)) == 0)：保證 n 是 2 的冪次方 (二進位中只有唯一的 1)
    // 3. ((n & 0x55555555) == n)：保證唯一的 1 落在奇數位元 (Bit 0, 2, 4, 6... 對應 4^0, 4^1, 4^2...)
    // ⚠️ 關鍵：位元運算子 & 的優先權低於關係運算子 ==，外層括號不可省略！
    return (n > 0) && ((n & (n - 1)) == 0) && ((n & 0x55555555) == n);
}

