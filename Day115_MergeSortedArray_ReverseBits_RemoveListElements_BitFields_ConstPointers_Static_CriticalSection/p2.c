#include <stdio.h>
#include <stdint.h>
#include <assert.h>

/**
 * LeetCode #190: Reverse Bits
 * 
 * 題目描述：
 * 顛倒給定的 32 位元無號整數 (32-bit unsigned integer) 的所有二進位位元 (Bits)。
 * 
 * 限制條件：
 * - 輸入為一個 32 位元的無號整數 n。
 * - 輸出必須為顛倒所有 32 位元後形成的 32 位元無號整數。
 * - 進階挑戰：你能否以 O(1) 的空間複雜度完成？若此函式會被大量高頻呼叫，你能否用分治遮罩將時間複雜度最佳化？
 * 
 * 範例 1:
 *   輸入: n = 00000010100101000001111010011100 (十進位 43261596)
 *   輸出:    00111001011110000010100101000000 (十進位 964176192)
 * 
 * 範例 2:
 *   輸入: n = 11111111111111111111111111111101 (十進位 4294967293)
 *   輸出:    10111111111111111111111111111111 (十進位 3221225471)
 * 
 * 範例 3:
 *   輸入: n = 1
 *   輸出: 2147483648 (即 1 << 31)
 */

uint32_t reverseBits(uint32_t n) {
    // 請在此處實現純白板程式碼
    n = (n >> 16) | (n << 16);
    // 2. 每 16 位中，交換高 8 位與低 8 位 (遮罩: 0x00FF00FF 與 0xFF00FF00)
    n = ((n & 0xFF00FF00) >> 8) | ((n & 0x00FF00FF) << 8);
    // 3. 每 8 位中，交換高 4 位與低 4 位 (遮罩: 0xF0F0F0F0 與 0x0F0F0F0F)
    n = ((n & 0xF0F0F0F0) >> 4) | ((n & 0x0F0F0F0F) << 4);
    // 4. 每 4 位中，交換高 2 位與低 2 位 (遮罩: 0xCCCCCCCC 與 0x33333333，因為 0xC=1100b, 0x3=0011b)
    n = ((n & 0xCCCCCCCC) >> 2) | ((n & 0x33333333) << 2);
    // 5. 每 2 位中，交換奇偶位元 (遮罩: 0xAAAAAAAA 與 0x55555555，因為 0xA=1010b, 0x5=0101b)
    n = ((n & 0xAAAAAAAA) >> 1) | ((n & 0x55555555) << 1);
    return n;
}

/*
 * =====================================================================================
 * 【面試亮點剖析 & 韌體底層考點】 (LeetCode #190: Reverse Bits)
 * =====================================================================================
 * 滿分解法亮點：
 * 1. 顛覆常規 O(32) 迴圈的神級分治術 (Divide & Conquer Bit Reversal)：
 *    絕大多數白板面試者只能寫出 32 次的 while / for 迴圈。
 *    你運用 5 次「二進位對摺術」：
 *    - 16-bit 對調 -> 8-bit 對調 -> 4-bit 對調 -> 2-bit 對調 -> 1-bit 對調
 *    - 在完全沒有分支 (Branchless)、無迴圈跳轉的情況下，僅用約 15 個 CPU cycles 完成！
 * 
 * 2. 韌體與通訊協定實務價值：
 *    - 串列傳輸 MSB/LSB 轉換：在 SPI、I2S、CAN bus、Modbus 協定轉換時，硬體資料流的位元順序常需要鏡像顛倒。
 *    - 硬體指令映射：在 ARM Cortex-M4/M7/M33 架構中，硬體有專門的單週期指令 `RBIT`。
 *      在純 C 語言實作中，這套 5 步分治法就是軟體模擬 `RBIT` 的業界最標準寫法！
 * =====================================================================================
 */

int main(void) {
    printf("=== Test P2: Reverse Bits ===\n");

    // Test 1: 43261596 -> 964176192
    assert(reverseBits(43261596U) == 964176192U);
    printf("Test 1 Passed: 43261596 -> 964176192\n");

    // Test 2: 4294967293 -> 3221225471
    assert(reverseBits(4294967293U) == 3221225471U);
    printf("Test 2 Passed: 4294967293 -> 3221225471\n");

    // Test 3: 1 -> 2147483648 (1 << 31)
    assert(reverseBits(1U) == 2147483648U);
    printf("Test 3 Passed: 1 -> 2147483648\n");

    // Test 4: 0 -> 0
    assert(reverseBits(0U) == 0U);
    printf("Test 4 Passed: 0 -> 0\n");

    // Test 5: 0xFFFFFFFF -> 0xFFFFFFFF
    assert(reverseBits(0xFFFFFFFFU) == 0xFFFFFFFFU);
    printf("Test 5 Passed: 0xFFFFFFFF -> 0xFFFFFFFF\n");

    printf("All P2 Local Tests Passed!\n");
    return 0;
}
