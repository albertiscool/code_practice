// ============================================================================
// 2. 極速最佳化版：Brian Kernighan's Algorithm (100% 滿分寫法)
// ============================================================================
int count_set_bits_fast(uint32_t n)
{
    int count = 0;
    while (n != 0)
    {
        n = n & (n - 1); // 每次消除最低位的 1，有幾個 1 就只跑幾次迴圈
        count++;
    }
    return count;
}