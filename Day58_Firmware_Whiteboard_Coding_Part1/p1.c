#include <stdint.h>

// ============================================================================
// 1. 基礎版：逐位元右移檢查 (修正版)
// ============================================================================
int count_set_bits(uint32_t n)
{
    int count = 0;
    while (n > 0)
    {
        if ((n & 1) == 1)
        {
            count++;
        }
        n = n >> 1; // 每次右移 1 位，直到 n 變成 0
    }
    return count;
}

