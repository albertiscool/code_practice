// 題目說明：編寫一個函式，輸入一個正整數 n，輸出點位二進制表示形式中值為 '1' 的位元個數
//           （也被稱為漢明重量 Hamming weight）。
// 範例 1：
//    輸入：n = 11 (二進制: 00000000000000000000000000001011)
//    輸出：3
// 範例 2：
//    輸入：n = 128 (二進制: 00000000000000000000000010000000)
//    輸出：1
// 範例 3：
//    輸入：n = 2147483645 (二進制: 01111111111111111111111111111101)
//    輸出：30
// 限制條件：
//    - 1 <= n <= 2^31 - 1
//    - 進階挑戰：你能否寫出時間複雜度僅與「1 的個數」相關的高效解法 (Brian Kernighan's Algorithm)？
// ============================================================================

int hammingWeight(int n) {
    // TODO: 請在純白板模式下完成實作 (請勿尋求提示)
    int count = 0;
    while(n != 0)
    {
        n &= (n-1);
        count++;
    }
    return count;
}

int main(void) {
    /* 測試測資 1: 11 -> 3 */
    int ans1 = hammingWeight(11);
    printf("測資 1 結果: %d (預期: 3)\n", ans1);

    /* 測試測資 2: 128 -> 1 */
    int ans2 = hammingWeight(128);
    printf("測資 2 結果: %d (預期: 1)\n", ans2);

    /* 測試測資 3: 2147483645 -> 30 */
    int ans3 = hammingWeight(2147483645);
    printf("測資 3 結果: %d (預期: 30)\n", ans3);

    return 0;
}
