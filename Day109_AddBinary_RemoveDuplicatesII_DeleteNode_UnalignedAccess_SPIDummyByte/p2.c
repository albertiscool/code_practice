/*
 * 你的實作（往前檢查兩格雙指標法）：
 * 核心原理：前 2 個元素無論如何都合法，從 index 2 開始。
 * 只要 candidate != nums[slow - 2]，就保證同一個數字最多只會出現兩次！
 */
int removeDuplicates(int* nums, int numsSize) {
    if (numsSize <= 2) return numsSize;

    int slow = 2; // 前 2 個數字一定合法，slow 從 index 2 開始準備寫入
    for (int fast = 2; fast < numsSize; fast++) {
        // 只要當前數字跟「已經確認合格的倒數第二個數字」不同，就合法！
        if (nums[fast] != nums[slow - 2]) {
            nums[slow] = nums[fast];
            slow++;
        }
    }
    return slow;
}

