#include <stdio.h>
#include <stdint.h>
#include <assert.h>

/**
 * LeetCode #191: Number of 1 Bits (Hamming Weight)
 * 
 * 題目描述：
 * 給定一個正整數 n，計算並回傳其二進位表達式中設置位（Set Bit，即數值為 1 的 bit）的個數。
 * 
 * 限制條件：
 * - 1 <= n <= 2^31 - 1
 * 
 * 範例 1:
 *   輸入: n = 11 (二進位: 00000000000000000000000000001011)
 *   輸出: 3
 * 
 * 範例 2:
 *   輸入: n = 128 (二進位: 00000000000000000000000010000000)
 *   輸出: 1
 * 
 * 範例 3:
 *   輸入: n = 2147483645 (二進位: 01111111111111111111111111111101)
 *   輸出: 30
 * 
 * 面試深意：
 * 群聯、瑞昱、聯發科位元運算第一名！考驗你能否不用跑 32 次迴圈，直接使用硬體位元級別的神技（Brian Kernighan 演算法）秒殺。
 */

int hammingWeight(int n) {
    // 請在此處實現純白板程式碼
    int count = 0;
    while(n != 0)
    {
        n = n & (n - 1);
        count++;
    }
    return count;
}

int main(void) {
    printf("=== Test P1: Number of 1 Bits ===\n");
    assert(hammingWeight(11) == 3);
    printf("Test 1 Passed: 11 has 3 bits\n");

    assert(hammingWeight(128) == 1);
    printf("Test 2 Passed: 128 has 1 bit\n");

    assert(hammingWeight(2147483645) == 30);
    printf("Test 3 Passed: 2147483645 has 30 bits\n");

    assert(hammingWeight(0) == 0);
    printf("Test 4 Passed: 0 has 0 bits\n");

    printf("All tests passed!\n");
    return 0;
}

