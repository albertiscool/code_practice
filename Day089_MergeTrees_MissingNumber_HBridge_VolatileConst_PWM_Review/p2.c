#include <stdio.h>
#include <stdlib.h>

// ============================================================================
// 題目 2【遺失的數字 (Missing Number - LeetCode #268)】
// 難度：🟢 Easy | 出題頻率：🔥🔥🔥🔥🔥 (各大 IC 設計廠位元運算/數論經典題)
// 題目說明：給定一個包含 [0, n] 中 n 個不同數字的陣列 nums，請找出並返回 [0, n] 中沒有出現在陣列中的那個數字。
//           你必須實現時間複雜度為 O(n)，且僅使用 O(1) 額外空間的解決方案。
// 範例 1：
//    輸入：nums = [3,0,1]
//    輸出：2
//    解釋：n = 3，數值範圍在 [0, 3] 內，共有 3 個數字，缺少了 2。
// 範例 2：
//    輸入：nums = [0,1]
//    輸出：2
//    解釋：n = 2，數值範圍在 [0, 2] 內，共有 2 個數字，缺少了 2。
// 範例 3：
//    輸入：nums = [9,6,4,2,3,5,7,0,1]
//    輸出：8
//    解釋：n = 9，數值範圍在 [0, 9] 內，缺少了 8。
// 限制條件：
//    - n == nums.length
//    - 1 <= n <= 10^4
//    - 0 <= nums[i] <= n
//    - nums 中的所有數字都獨一無二
// ============================================================================

int missingNumber(int* nums, int numsSize) {
    // 解法 1（IC 設計廠首選：XOR 位元運算，絕不發生整數溢位）：
    // 利用 a ^ a = 0 與 a ^ 0 = a 的特性，
    // 將 [0, n] 的所有數字與陣列中的所有數字全部做 XOR，
    // 出現兩次的數字全部抵消歸零，最後留下的就是遺失的數字！
    int res = numsSize;
    for (int i = 0; i < numsSize; i++) {
        res ^= (i ^ nums[i]);
    }
    return res;
}

