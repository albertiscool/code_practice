#include <stdio.h>
#include <stdint.h>

// ============================================================================
// 題目 2【位元 1 的個數 / 漢明重量 (Number of 1 Bits - LeetCode #191)】
// 難度：🟢 系統廠高頻基本題 | 出題頻率：🔥🔥🔥🔥🔥 (系統廠/科技廠韌體位元運算必備)
// 題目說明：編寫一個函式，輸入一個 32 位元無號整數 n，返回其二進位表示中「1」的個數（也稱為漢明重量）。
// 範例 1：
//    輸入：n = 11 (二進位 00000000000000000000000000001011)
//    輸出：3
// 範例 2：
//    輸入：n = 128 (二進位 00000000000000000000000010000000)
//    輸出：1
// 範例 3：
//    輸入：n = 2147483645 (二進位 01111111111111111111111111111101)
//    輸出：30
// 限制條件：
//    - 輸入必須是 32 位元的二進位串
//    - ⚠️ 進階挑戰：能否利用位元運算技巧（例如 n & (n - 1)），讓迴圈次數僅取決於「1 的個數」，而非死板地跑滿 32 次？
// ============================================================================

int hammingWeight(uint32_t n) {
    // TODO: 請在純白板模式下完成實作 (請勿尋求提示)
    int count = 0;
    while(n != 0)
    {
        n = n & (n - 1);
        count++;
    }
    return count;
}

int main(void) {
    /* 測試測資 1: 11 -> 3 */
    printf("測資 1 (n=11)        : %d (預期: 3)\n", hammingWeight(11));

    /* 測試測資 2: 128 -> 1 */
    printf("測資 2 (n=128)       : %d (預期: 1)\n", hammingWeight(128));

    /* 測試測資 3: 0 -> 0 (邊界) */
    printf("測資 3 (n=0)         : %d (預期: 0)\n", hammingWeight(0));

    /* 測試測資 4: 0xFFFFFFFF (全1) -> 32 */
    printf("測資 4 (n=0xFFFFFFFF): %d (預期: 32)\n", hammingWeight(0xFFFFFFFF));

    return 0;
}
