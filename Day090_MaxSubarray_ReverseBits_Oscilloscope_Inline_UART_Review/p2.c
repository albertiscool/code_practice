#include <stdio.h>
#include <stdint.h>

// ============================================================================
// 題目 2【顛倒二進位位元 (Reverse Bits - LeetCode #190)】
// 難度：🟢 Easy | 出題頻率：🔥🔥🔥🔥🔥 (各大 IC 設計廠/韌體廠面試必考位元反轉題)
// 題目說明：顛倒給定的 32 位元無號整數的二進位位元。
// 範例 1：
//    輸入：n = 00000010100101000001111010011100 (十進制: 43261596)
//    輸出：n = 00111001011110000010100101000000 (十進制: 964176192)
//    解釋：輸入的二進制串顛倒後得到輸出的二進制串。
// 範例 2：
//    輸入：n = 11111111111111111111111111111101
//    輸出：n = 10111111111111111111111111111111
// 限制條件：
//    - 輸入必須是長度為 32 的二進制位元字串（uint32_t）。
//    - 空間複雜度必須為 O(1)。
// ============================================================================

uint32_t reverseBits(uint32_t n) {
    /*
     * 正確解答 (位元反轉 Bitwise Manipulation):
     * 關鍵在於「先將 result 左移騰出空間，再將 n 的當前最低位 (LSB) 填入」。
     * 迴圈執行 32 次：
     * 第 0 次進來的位元會在後續經歷 31 次左移，最終到達第 31 位 (MSB)。
     * 第 31 次進來的位元剛好不被後續左移，停留在第 0 位 (LSB)。
     */
    uint32_t result = 0;
    for (int i = 0; i < 32; i++) {
        result = (result << 1) | (n & 1);
        n >>= 1;
    }
    return result;
}

/* ============================================================================
 * ❌ 原始實作盲點分析 (已保留供複習檢討):
 * ============================================================================
 * uint32_t reverseBits_wrong(uint32_t n) {
 *     uint32_t result = 0;
 *     for(int i = 0; i < 32; i++)
 *     {
 *         result += (n & 1);     // ⚠️ 盲點：先將位元加進去，才執行 result << 1
 *         n = n >> 1;
 *         result = result << 1;  // 這會導致在最後一次迴圈 (i=31) 時，最後進來的位元
 *                                // 被多左移了 1 次 (停在 bit 1 而不是 bit 0)，
 *                                // 最早進來的 bit 0 則被左移了 32 次而發生 32-bit 溢位歸零！
 *                                // 結果：測資 1 剛好是預期的 2 倍 (多 shift 1 次)，測資 2 溢位變 0。
 *     }
 *     return result;
 * }
 * ============================================================================ */

int main(void) {
    /* 測試測資 1: 43261596 -> 964176192 */
    uint32_t n1 = 43261596U;
    uint32_t ans1 = reverseBits(n1);
    printf("測資 1 結果: %u (預期: 964176192)\n", ans1);

    /* 測試測資 2: 1 -> 2147483648 (最高位元變 1) */
    uint32_t n2 = 1U;
    uint32_t ans2 = reverseBits(n2);
    printf("測資 2 結果: %u (預期: 2147483648)\n", ans2);

    return 0;
}
