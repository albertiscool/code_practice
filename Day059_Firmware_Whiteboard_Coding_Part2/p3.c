#include <stdio.h>
#include <stdint.h>
#include <stdbool.h>

// ============================================================================
// 任務 1：檢查當前系統是 Little-Endian 還是 Big-Endian (指標轉型法)
// ============================================================================
bool is_little_endian(void)
{
    uint32_t x = 0x0001;
    uint8_t *y = (uint8_t *)&x; 
    return (*y == 1);
}

// ============================================================================
// 任務 1 加分寫法：使用 Union (共用體) 解法
// ============================================================================
bool is_little_endian_union(void)
{
    union {
        uint32_t val;
        uint8_t bytes[4];
    } u;
    
    u.val = 1;
    return (u.bytes[0] == 1);
}

// ============================================================================
// 任務 2：32 位元大小端 Byte 反轉 (位元遮罩與位移法 - 最推薦寫法)
// ============================================================================
uint32_t swap_endian(uint32_t val)
{
    // 例如輸入 val = 0x12345678
    return ((val & 0x000000FF) << 24) | // 取出 0x78 往左移 24 位 ➡️ 0x78000000
           ((val & 0x0000FF00) << 8)  | // 取出 0x56 往左移 8 位  ➡️ 0x00560000
           ((val & 0x00FF0000) >> 8)  | // 取出 0x34 往右移 8 位  ➡️ 0x00003400
           ((val & 0xFF000000) >> 24);  // 取出 0x12 往右移 24 位 ➡️ 0x00000012
    // 合併結果 = 0x78563412
}

// ============================================================================
// 任務 2 替代寫法：使用 Union (共用體) 重新組合 Byte
// ============================================================================
uint32_t swap_endian_union(uint32_t val)
{
    union {
        uint32_t num;
        uint8_t bytes[4];
    } u;
    
    u.num = val; // 1. 先把傳入的 val 賦值給 union
    
    // 2. 將 4 個 Byte 重新倒序拼湊起來 (注意用位元 OR '|')
    return ((uint32_t)u.bytes[0] << 24) |
           ((uint32_t)u.bytes[1] << 16) |
           ((uint32_t)u.bytes[2] << 8)  |
           ((uint32_t)u.bytes[3]);
}

