/**
 * ============================================================================
 * 【Day 108 - 題目三】同構字串 (LeetCode #205 - Isomorphic Strings)
 * 【考試頻率】群聯 (Phison) SSD 控制器通訊查表 / 系統廠 經典 ASCII LUT 題
 * 【LeetCode 難度】Easy (字元映射與查表法)
 * ============================================================================
 * 【題目說明】
 * 給定兩個字串 s 與 t，請判斷它們是否為「同構（Isomorphic）」。
 * 
 * 如果 s 中的字元可以經過某種一對一的映射替換，使得 s 變為 t，則稱這兩個字串是同構的。
 * 每個出現的字元都必須映射到另一個字元，同時保留原始字元的順序。
 * ⚠️ 限制：兩個不同的字元不能映射到同一個字元上（必須雙向一一對應 Bijection），
 * 且字元可以映射到它自己。
 * 
 * 【範例 1】
 * 輸入: s = "egg", t = "add"
 * 輸出: true
 * 解釋: 'e' 映射到 'a'，'g' 映射到 'd'。
 * 
 * 【範例 2】
 * 輸入: s = "foo", t = "bar"
 * 輸出: false
 * 解釋: 'o' 不能同時映射到 'a' 與 'r'。
 * 
 * 【範例 3】
 * 輸入: s = "paper", t = "title"
 * 輸出: true
 * 
 * 【範例 4】
 * 輸入: s = "badc", t = "baba"
 * 輸出: false
 * 解釋: 'd' 映射到 'b'，但 'b' 已經被 'b' 映射了，造成多對一衝突。
 * 
 * 【限制條件】
 * 1. 1 <= s.length <= 5 * 10^4
 * 2. t.length == s.length
 * 3. s 和 t 由任意有效的 ASCII 字元組成。
 * ============================================================================
 */

bool isIsomorphic(char* s, char* t) {
    int len = strlen(s);
    // 💡 韌體小防護：使用 unsigned char 避免 ASCII > 127 時轉為負數造成陣列越界
    unsigned char map_s[256] = {0}; // 記錄 s 的字元映射到誰
    unsigned char map_t[256] = {0}; // 記錄 t 的字元映射到誰

    for (int i = 0; i < len; i++) {
        unsigned char c1 = (unsigned char)s[i];
        unsigned char c2 = (unsigned char)t[i];

        // 💡 關鍵判斷修正：若兩者都「尚未登記過」（== 0），建立雙向唯一綁定
        if (map_s[c1] == 0 && map_t[c2] == 0) {
            map_s[c1] = c2;
            map_t[c2] = c1;
        } else {
            // 若其中一方已經登記過，必須嚴格檢查是否與先前紀錄完全吻合
            if (map_s[c1] != c2 || map_t[c2] != c1) {
                return false;
            }
        }
    }
    return true;
}

