/**
 * ============================================================================
 * 【Day 108 - 題目一】交替位元二進位數 (LeetCode #693 - Binary Number with Alternating Bits)
 * 【考試頻率】群聯 (Phison) SSD 韌體 / 瑞昱 (Realtek) / 系統廠 暫存器測試模式 (Pattern Check) 高頻題
 * 【LeetCode 難度】Easy (位元邏輯操作)
 * ============================================================================
 * 【題目說明】
 * 給定一個正整數 n，檢查它的二進位表示中，相鄰的兩個二進位位元是否「永遠不相同」
 * （即相鄰的 bit 必須在 0 與 1 之間交替出現，例如 10101... 或 01010...）。
 * 
 * 若相鄰位元皆不相同，回傳 true；否則回傳 false。
 * 
 * 【範例 1】
 * 輸入: n = 5
 * 輸出: true
 * 解釋: 5 的二進位表示為 101，相鄰位元交替出現。
 * 
 * 【範例 2】
 * 輸入: n = 7
 * 輸出: false
 * 解釋: 7 的二進位表示為 111，存在連續的 1。
 * 
 * 【範例 3】
 * 輸入: n = 11
 * 輸出: false
 * 解釋: 11 的二進位表示為 1011，最後兩位皆為 1。
 * 
 * 【限制條件】
 * 1. 1 <= n <= 2^31 - 1
 * ============================================================================
 */

/*
 * 你的實作（滑動位元比對法，一發入魂 0 ms Beats 100% AC）：
 * 核心思路：取出當前最低位 (n & 1) 與次低位 ((n >> 1) & 1) 比對，不相等則持續右移，遇相同立即回傳 false。
 */
bool hasAlternatingBits(int n) {
    while (n != 0) {
        if ((n & 1) != ((n >> 1) & 1)) {
            n = n >> 1;
        } else {
            return false;
        }
    }
    return true;
}

