#include <stdio.h>

/**
 * ============================================================================
 * 【Day 104 - 題目二】漢明距離 (LeetCode #461 - Hamming Distance)
 * 【考試頻率】群聯 (Phison) / 系統廠 (廣達、緯創、和碩) 必考位元運算題
 * 【LeetCode 難度】Easy (初階精準題)
 * ============================================================================
 * 【題目說明】
 * 兩個整數之間的「漢明距離」是指這兩個數字對應的二進位位元不同的位置個數。
 * 給定兩個整數 x 和 y，請計算並回傳它們之間的漢明距離。
 * 
 * 【範例 1】
 * 輸入: x = 1, y = 4
 * 輸出: 2
 * 解釋:
 * 1   (0 0 0 1)
 * 4   (0 1 0 0)
 *        ↑   ↑
 * 共有 2 個位置的位元不同。
 * 
 * 【範例 2】
 * 輸入: x = 3, y = 1
 * 輸出: 1
 * 解釋:
 * 3   (0 0 1 1)
 * 1   (0 0 0 1)
 *          ↑
 * 共有 1 個位置的位元不同。
 * 
 * 【限制條件】
 * 1. 0 <= x, y <= 2^31 - 1
 * ============================================================================
 */

int hammingDistance(int x, int y) {
    if (x == y) {
        return 0;
    }
    int a = x ^ y;
    int count = 0;
    while (a > 0) {
        a = a & (a - 1);
        count++;
    }
    return count;
}

